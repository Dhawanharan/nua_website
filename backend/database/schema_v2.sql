-- 1. Create admin_users table
CREATE TABLE IF NOT EXISTS public.admin_users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(150) NOT NULL,
  email VARCHAR(255) UNIQUE NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  privilege VARCHAR(20) NOT NULL DEFAULT 'admin' CHECK (privilege IN ('super_admin', 'admin')),
  committee_role VARCHAR(100) NOT NULL,
  phone VARCHAR(50),
  avatar_url TEXT,
  is_active BOOLEAN DEFAULT TRUE,
  last_login TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. Create committee_members table (ExCo and Area Representatives)
CREATE TABLE IF NOT EXISTS public.committee_members (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(150) NOT NULL,
  role VARCHAR(150) NOT NULL,
  category VARCHAR(50) NOT NULL DEFAULT 'exco' CHECK (category IN ('exco', 'rep')),
  area VARCHAR(100),
  university VARCHAR(150),
  image_url TEXT,
  display_order INT DEFAULT 0,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 3. Create site_settings table (Contact details & social handles)
CREATE TABLE IF NOT EXISTS public.site_settings (
  id INT PRIMARY KEY DEFAULT 1,
  email VARCHAR(255) DEFAULT 'nuwaraeliya.undergraduates@gmail.com',
  phone VARCHAR(100) DEFAULT '+94 77 123 4567',
  address TEXT DEFAULT 'Nuwara Eliya, Sri Lanka',
  facebook_url TEXT DEFAULT 'https://facebook.com',
  instagram_url TEXT DEFAULT 'https://instagram.com',
  linkedin_url TEXT DEFAULT 'https://linkedin.com',
  youtube_url TEXT DEFAULT 'https://youtube.com',
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 4. Grant table privileges and configure Row Level Security (RLS)
GRANT ALL ON TABLE public.admin_users TO anon, authenticated, service_role;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;

GRANT ALL ON TABLE public.committee_members TO anon, authenticated, service_role;
GRANT ALL ON TABLE public.site_settings TO anon, authenticated, service_role;

ALTER TABLE public.admin_users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.committee_members ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.site_settings ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Full access admin_users" ON public.admin_users;
CREATE POLICY "Full access admin_users" ON public.admin_users FOR ALL USING (true);

DROP POLICY IF EXISTS "Full access committee_members" ON public.committee_members;
CREATE POLICY "Full access committee_members" ON public.committee_members FOR ALL USING (true);

DROP POLICY IF EXISTS "Full access site_settings" ON public.site_settings;
CREATE POLICY "Full access site_settings" ON public.site_settings FOR ALL USING (true);

-- Ensure site_settings row 1 exists
INSERT INTO public.site_settings (id) VALUES (1) ON CONFLICT (id) DO NOTHING;
